#requires -Version 5.1
<#
  冥零工作台 · 把 QQ 接入组件的官方原版包备到 pack\login（给 -BundleLogin 用）

  默认不做任何事，只把 installer\login_auto.iss 写成「不内置」；
  加 -Enable 才会去准备那份 zip，并写成「内置」。

    powershell -NoProfile -ExecutionPolicy Bypass -File installer\prepare-login.ps1
        写 BundleLogin=0（不内置，正常出包）。
    powershell ... -Enable
        在下列位置找官方原版 zip（按 SHA256 认文件，不改名也不改内容），校验通过后
        复制到 pack\login\；一个都没找到且没加 -Offline 就按清单里的地址下载。
    powershell ... -Enable -Offline
        只用本地已有的副本，找不到就失败（CI/断网出包用）。

  校验基准不在本脚本里写死：版本、地址、SHA256、字节数全部读 tools\components.json
  里那个 QQ 接入组件（id 仍是 snowluma），跟 bootstrap.ps1 安装时用的那一份完全一致，
  避免两处各记一个哈希。

  产物是一份「原版 zip 一字节未改」的副本，只是落了中性文件名，装包列表里不会出现上游名字。
#>
[CmdletBinding()]
param(
    [switch]$Enable,
    [switch]$Offline,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$manifestPath = Join-Path $repo 'tools\components.json'
$issPath = Join-Path $PSScriptRoot 'login_auto.iss'
$stageDir = Join-Path $repo 'pack\login'

function Write-Iss([int]$Bundle, [string]$RelPath, [string]$Ver, [string]$Sha) {
    $lines = @()
    $lines += '; generated by installer\prepare-login.ps1 - do not edit'
    $lines += '#define BundleLogin ' + $Bundle
    if ($Bundle -eq 1) {
        $lines += '#define LoginZip "' + $RelPath + '"'
        $lines += '#define LoginVer "' + $Ver + '"'
        $lines += '#define LoginSha "' + $Sha + '"'
    }
    [IO.File]::WriteAllText($issPath, (($lines -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding $false))
}

if (-not $Enable) {
    Write-Iss 0 '' '' ''
    Write-Host '[bundle] 不内置（BundleLogin=0）'
    exit 0
}

if (-not (Test-Path -LiteralPath $manifestPath)) { throw "缺少 tools\components.json：$manifestPath" }
$manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$comp = @($manifest.components | Where-Object { $_.id -eq 'snowluma' })[0]
if (-not $comp) { throw 'tools\components.json 里没有 QQ 接入组件（id snowluma）' }

$step = @($comp.install.steps | Where-Object { $_.kind -eq 'download' })[0]
if (-not $step) { throw 'QQ 接入组件没有 download 步骤' }
$ver = [string]$comp.version
$sha = ([string]$step.sha256).ToUpper()
$size = 0
try { if ($step.size) { $size = [long]$step.size } } catch { }
if (-not $sha -or $sha.Length -ne 64) { throw 'QQ 组件的 download 步骤缺少 64 位 sha256，拒绝内置' }

# 舞台里用中性文件名，安装包的文件列表里不出现上游名字；内容是原版 zip，一个字节都不动。
$stageLeaf = 'login-client-v' + $ver + '-win-x64.zip'
$stagePath = Join-Path $stageDir $stageLeaf
$upstreamLeaf = 'SnowLuma-v' + $ver + '-win-x64.zip'

# 候选目录：先看已经备好的舞台，再看验收缓存、工具缓存、临时目录。
# 这些都不进 Git，所以换台机器出包时大概率要联网下一次（-Offline 时就直说失败）。
# 按 SHA256 认人，不看文件名——上游改了发布名也不影响。
$candidates = @(
    $stageDir,
    (Join-Path $repo 'acceptance\cache'),
    (Join-Path $repo 'tools\dl'),
    (Join-Path $repo 'tmp')
)

function Test-Package([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    $len = (Get-Item -LiteralPath $Path).Length
    if ($size -gt 0 -and $len -ne $size) { return $false }
    $h = (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToUpper()
    return ($h -eq $sha)
}

$found = ''
# 舞台里已经有一份（可能叫中性名）就直接用
foreach ($c in $candidates) {
    if (-not (Test-Path -LiteralPath $c -PathType Container)) { continue }
    foreach ($f in @(Get-ChildItem -LiteralPath $c -File -ErrorAction SilentlyContinue)) {
        if (Test-Package $f.FullName) { $found = $f.FullName; break }
    }
    if ($found) { break }
}

if (-not $found) {
    if ($Offline) {
        throw ('离线模式：本机没有校验通过的组件原版包（找过：' + (($candidates | ForEach-Object { $_ }) -join '、') + '，要找的是 ' + $upstreamLeaf + '）')
    }
    $urls = @()
    foreach ($u in @($step.urls)) { if ($u) { $urls += [string]$u } }
    if ($urls.Count -eq 0) { $urls = @([string]$step.url) }
    New-Item -ItemType Directory -Force -Path $stageDir | Out-Null
    $tmp = $stagePath + '.part'
    $ok = $false
    foreach ($u in $urls) {
        Write-Host ('[bundle] 下载 ' + $u)
        try {
            & curl.exe -L -f -sS --retry 3 --retry-delay 2 --connect-timeout 15 -o $tmp $u
            if ($LASTEXITCODE -ne 0) { throw ('curl 退出码 ' + $LASTEXITCODE) }
            if (Test-Package $tmp) { Move-Item -LiteralPath $tmp -Destination $stagePath -Force; $ok = $true; break }
            Write-Host '  [失败] 下载下来的文件 SHA256 对不上'
        } catch {
            Write-Host ('  [失败] ' + $_.Exception.Message)
        }
    }
    Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    if (-not $ok) { throw ('没能拿到校验通过的组件原版包（' + $upstreamLeaf + '），无法内置') }
    $found = $stagePath
}

if ($found -ne $stagePath) {
    New-Item -ItemType Directory -Force -Path $stageDir | Out-Null
    if ($Force -or -not (Test-Path -LiteralPath $stagePath)) {
        Copy-Item -LiteralPath $found -Destination $stagePath -Force
        Write-Host ('[bundle] 已备到 ' + $stagePath)
    } else {
        Write-Host ('[bundle] 舞台上已有同名文件，保留：' + $stagePath)
    }
}

$mb = [math]::Round((Get-Item -LiteralPath $stagePath).Length / 1MB, 1)
Write-Iss 1 ('..\pack\login\' + $stageLeaf) $ver $sha
Write-Host ('[bundle] 内置 QQ 接入组件 {0}（{1} MB，SHA256 {2}…）' -f $ver, $mb, $sha.Substring(0, 12))
Write-Host '[bundle] 提示：上游许可协议 §5.4 要求「并入第三方安装包」须事先取得书面授权，请自行确认。'
exit 0
