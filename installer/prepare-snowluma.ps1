#requires -Version 5.1
<#
  冥零工作台 · 把 SnowLuma 官方原版包备到 pack\snowluma（给 -BundleSnowLuma 用）

  默认不做任何事，只把 installer\snowluma_auto.iss 写成「不内置」；
  加 -Enable 才会去准备那份 zip，并写成「内置」。

    powershell -NoProfile -ExecutionPolicy Bypass -File installer\prepare-snowluma.ps1
        写 BundleSnowLuma=0（不内置，正常出包）。
    powershell ... -Enable
        在下列位置找官方原版 zip（顺序即优先级），校验 SHA256 通过后复制到
        pack\snowluma\；一个都没找到且没加 -Offline 就按清单里的地址下载。
    powershell ... -Enable -Offline
        只用本地已有的副本，找不到就失败（CI/断网出包用）。

  校验基准不在本脚本里写死：版本、地址、SHA256、字节数全部读 tools\components.json
  的 snowluma 组件，跟 bootstrap.ps1 安装时用的那一份完全一致，避免两处各记一个哈希。
#>
[CmdletBinding()]
param(
    [switch]$Enable,
    [switch]$Offline,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$manifestPath = Join-Path $repo 'tools\components.json'
$issPath = Join-Path $PSScriptRoot 'snowluma_auto.iss'
$stageDir = Join-Path $repo 'pack\snowluma'

function Write-Iss([int]$Bundle, [string]$RelPath, [string]$Ver, [string]$Sha) {
    $lines = @()
    $lines += '; generated by installer\prepare-snowluma.ps1 - do not edit'
    $lines += '#define BundleSnowLuma ' + $Bundle
    if ($Bundle -eq 1) {
        $lines += '#define SnowLumaZip "' + $RelPath + '"'
        $lines += '#define SnowLumaVer "' + $Ver + '"'
        $lines += '#define SnowLumaSha "' + $Sha + '"'
    }
    [IO.File]::WriteAllText($issPath, (($lines -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding $false))
}

if (-not $Enable) {
    Write-Iss 0 '' '' ''
    Write-Host '[snowluma] 不内置（BundleSnowLuma=0）'
    exit 0
}

if (-not (Test-Path -LiteralPath $manifestPath)) { throw "缺少 tools\components.json：$manifestPath" }
$manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$comp = @($manifest.components | Where-Object { $_.id -eq 'snowluma' })[0]
if (-not $comp) { throw 'tools\components.json 里没有 snowluma 组件' }

$step = @($comp.install.steps | Where-Object { $_.kind -eq 'download' })[0]
if (-not $step) { throw 'snowluma 组件没有 download 步骤' }
$ver = [string]$comp.version
$sha = ([string]$step.sha256).ToUpper()
$size = 0
try { if ($step.size) { $size = [long]$step.size } } catch { }
if (-not $sha -or $sha.Length -ne 64) { throw 'snowluma 的 download 步骤缺少 64 位 sha256，拒绝内置' }

$leaf = 'SnowLuma-v' + $ver + '-win-x64.zip'
$stagePath = Join-Path $stageDir $leaf

# 候选：先看已经备好的舞台，再看验收缓存、工具缓存、安装缓存。
# 这些都不进 Git，所以换台机器出包时大概率要联网下一次（-Offline 时就直说失败）。
$candidates = @(
    $stagePath,
    (Join-Path $repo ('acceptance\cache\' + $leaf)),
    (Join-Path $repo ('tools\dl\' + $leaf)),
    (Join-Path $repo ('tmp\' + $leaf))
)

function Test-Package([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    $len = (Get-Item -LiteralPath $Path).Length
    if ($size -gt 0 -and $len -ne $size) {
        Write-Host ('  [跳过] {0} 大小不对：{1} 字节，清单写的是 {2}' -f (Split-Path -Leaf $Path), $len, $size)
        return $false
    }
    $h = (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToUpper()
    if ($h -ne $sha) {
        Write-Host ('  [跳过] {0} SHA256 对不上' -f (Split-Path -Leaf $Path))
        return $false
    }
    return $true
}

$found = ''
foreach ($c in $candidates) {
    if (-not $c) { continue }
    if (Test-Package $c) { $found = $c; break }
}

if (-not $found) {
    if ($Offline) { throw ('离线模式：本机没有校验通过的 ' + $leaf + '（找过：' + ($candidates -join '、') + '）') }
    $urls = @()
    foreach ($u in @($step.urls)) { if ($u) { $urls += [string]$u } }
    if ($urls.Count -eq 0) { $urls = @([string]$step.url) }
    New-Item -ItemType Directory -Force -Path $stageDir | Out-Null
    $tmp = $stagePath + '.part'
    $ok = $false
    foreach ($u in $urls) {
        Write-Host ('[snowluma] 下载 ' + $u)
        try {
            & curl.exe -L -f -sS --retry 3 --retry-delay 2 --connect-timeout 15 -o $tmp $u
            if ($LASTEXITCODE -ne 0) { throw ('curl 退出码 ' + $LASTEXITCODE) }
            if (Test-Package $tmp) { Move-Item -LiteralPath $tmp -Destination $stagePath -Force; $ok = $true; break }
        } catch {
            Write-Host ('  [失败] ' + $_.Exception.Message)
        }
    }
    Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    if (-not $ok) { throw ('没能拿到校验通过的 ' + $leaf + '，无法内置') }
    $found = $stagePath
}

if ($found -ne $stagePath) {
    New-Item -ItemType Directory -Force -Path $stageDir | Out-Null
    if ($Force -or -not (Test-Path -LiteralPath $stagePath)) {
        Copy-Item -LiteralPath $found -Destination $stagePath -Force
        Write-Host ('[snowluma] 已备到 ' + $stagePath)
    } else {
        Write-Host ('[snowluma] 舞台上已有同名文件，保留：' + $stagePath)
    }
}

$mb = [math]::Round((Get-Item -LiteralPath $stagePath).Length / 1MB, 1)
Write-Iss 1 ('..\pack\snowluma\' + $leaf) $ver $sha
Write-Host ('[snowluma] 内置 SnowLuma {0}（{1} MB，SHA256 {2}…）' -f $ver, $mb, $sha.Substring(0, 12))
Write-Host '[snowluma] 提示：上游 EULA §5.4 要求「并入第三方安装包」须事先取得书面授权，请自行确认。'
exit 0
